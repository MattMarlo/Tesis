    <h2>3. Datos que podemos recopilar</h2>

    <p>Dependiendo del servicio solicitado, podremos recopilar:</p>

    <ul>
        <li>Nombres y apellidos.</li>
        <li>Número de cédula, pasaporte o documento de identificación.</li>
        <li>Número de teléfono y cuenta de WhatsApp.</li>
