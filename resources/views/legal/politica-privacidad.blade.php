        <li>Fechas de viaje y preferencias de atención.</li>
        <li>Comprobantes de pago enviados como imagen o documento.</li>
        <li>Mensajes intercambiados con el chatbot o con los asesores.</li>
        <li>Datos técnicos básicos necesarios para el funcionamiento y
            seguridad del sistema.</li>
    </ul>

    <p>
        Passion Travel solicitará únicamente los datos adecuados, pertinentes
        y necesarios para cada finalidad.
    </p>

    <h2>4. Finalidades del tratamiento</h2>

    <p>Los datos podrán ser utilizados para:</p>

    <ul>
        <li>Mostrar información sobre paquetes turísticos y disponibilidad.</li>
        <li>Atender consultas realizadas mediante WhatsApp o el sitio web.</li>
        <li>Gestionar solicitudes de contacto y atención personalizada.</li>
        <li>Generar y administrar prerreservas y reservas.</li>
        <li>Identificar al cliente y consultar información de su viaje.</li>
        <li>Recibir comprobantes de pago para su posterior revisión humana.</li>
        <li>Enviar confirmaciones, avisos y recordatorios relacionados con
            pagos, reservas y fechas de viaje.</li>
        <li>Brindar soporte antes, durante y después del viaje.</li>
        <li>Prevenir usos indebidos y proteger la seguridad del sistema.</li>
        <li>Cumplir obligaciones legales, contractuales y administrativas.</li>
    </ul>

    <h2>5. Chatbot y decisiones automatizadas</h2>

    <p>
        Passion Travel utiliza herramientas de automatización para responder
        consultas y orientar a los usuarios. El chatbot puede procesar los
        mensajes recibidos, identificar la opción seleccionada y consultar
        información del sistema.
    </p>

    <p>
        El chatbot no confirma por sí solo la validez de pagos ni adopta
        decisiones que produzcan efectos jurídicos significativos. Los
        comprobantes enviados quedan pendientes de revisión y aprobación por
        parte de una persona autorizada de Passion Travel.
    </p>

    <h2>6. Consentimiento</h2>

    <p>
        Cuando el tratamiento se base en el consentimiento, este será
        solicitado de manera libre, específica, informada e inequívoca.
        Antes de recopilar información mediante el chatbot, el usuario podrá
        aceptar o rechazar el tratamiento de sus datos.
    </p>

    <p>
        El usuario puede retirar su consentimiento en cualquier momento. La
        revocatoria no afecta la legitimidad del tratamiento efectuado antes
        de su retiro.
    </p>

