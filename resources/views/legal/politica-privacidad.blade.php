        <li>Servicios de correo electrónico.</li>
        <li>Proveedores de inteligencia artificial cuando sean necesarios
            para interpretar consultas.</li>
    </ul>

    <p>
        Los datos no serán vendidos. Solo serán comunicados cuando resulte
        necesario para prestar el servicio, exista autorización del titular
        o una obligación legal.
    </p>

    <h2>8. Transferencias internacionales</h2>

    <p>
        Algunos proveedores tecnológicos pueden almacenar o procesar
        información fuera de Ecuador. Passion Travel procurará que estos
        tratamientos se realicen con garantías adecuadas de privacidad,
        seguridad y confidencialidad.
    </p>

    <h2>9. Conservación de los datos</h2>

    <p>
        Los datos serán conservados únicamente durante el tiempo necesario
        para cumplir las finalidades indicadas, gestionar la relación con el
        cliente y atender obligaciones legales o posibles reclamaciones.
        Cuando la información deje de ser necesaria, será eliminada,
        anonimizada o bloqueada conforme corresponda.
    </p>

    <h2>10. Comprobantes de pago</h2>

    <p>
        Los comprobantes enviados mediante WhatsApp se almacenarán como
        documentos pendientes de revisión. Su recepción no significa que el
        pago haya sido aprobado o registrado definitivamente.
    </p>

    <p>
        Una persona autorizada verificará la información y posteriormente
        confirmará si el pago es válido.
    </p>

    <h2>11. Seguridad de la información</h2>

    <p>
        Passion Travel aplicará medidas técnicas y organizativas razonables
        para evitar la pérdida, alteración, divulgación, acceso o tratamiento
        no autorizado de los datos personales.
    </p>

    <p>
        Sin embargo, ningún sistema conectado a Internet puede garantizar
        seguridad absoluta. Ante un incidente relevante, se aplicarán las
        medidas de respuesta y notificación exigidas por la normativa.
    </p>

